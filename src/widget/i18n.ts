import { create } from 'zustand'
import { setFmtLang, plural, type Lang } from '../lib/format'

/* Widget language. Russian strings are the keys; Kazakh comes from KK below.
   Anything missing (for example texts the owner typed in the CRM) stays in Russian. */
const KEY = 'moloko.lang'
const initial = (): Lang => {
  try {
    const q = new URLSearchParams(location.search).get('lang')
    if (q === 'kk' || q === 'ru') return q
    const s = localStorage.getItem(KEY)
    if (s === 'kk' || s === 'ru') return s
  } catch { /* */ }
  return 'ru'
}
const apply = (l: Lang) => { setFmtLang(l); try { document.documentElement.lang = l; localStorage.setItem(KEY, l) } catch { /* */ } }

export const useLang = create<{ lang: Lang; set: (l: Lang) => void }>(set => {
  const l = initial(); apply(l)
  return { lang: l, set: (x: Lang) => { apply(x); set({ lang: x }) } }
})

const fill = (s: string, v?: Record<string, string | number>) => v ? s.replace(/\{(\w+)\}/g, (m, k) => (k in v ? String(v[k]) : m)) : s

/** translate a Russian UI string; `{name}` placeholders are filled from v */
export function t(ru: string, v?: Record<string, string | number>) {
  const s = useLang.getState().lang === 'kk' ? KK[ru] ?? ru : ru
  return fill(s, v)
}
/** Russian plural in ru; Kazakh nouns don't change after numbers */
export const pl = (n: number, one: string, few: string, many: string) => useLang.getState().lang === 'kk' ? t(one) : plural(n, one, few, many)

/** price lines from quote() */
export function tLine(s: string) {
  if (useLang.getState().lang !== 'kk') return s
  let m
  if ((m = s.match(/^Зал (.+) · (\d+) ч$/))) return `${m[1]} залы · ${m[2]} сағ`
  if ((m = s.match(/^Ночные часы · (\d+) ч$/))) return `Түнгі сағаттар · ${m[1]} сағ`
  if ((m = s.match(/^Гости сверх (\d+) · (\d+) чел\.$/))) return `${m[1]} адамнан артық қонақтар · ${m[2]} адам`
  if ((m = s.match(/^(.+) · (\d+) ч$/))) return `${t(m[1])} · ${m[2]} сағ`
  return t(s)
}

